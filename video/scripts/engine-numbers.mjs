#!/usr/bin/env node
// engine-numbers.mjs — regenerate the numbers block in docs/ENGINE.md from src/lib/theme.ts (so the doc never drifts).
// The block sits between <!-- numbers:begin --> and <!-- numbers:end -->. Run after changing theme tokens:
//   node scripts/engine-numbers.mjs          # rewrite the block
//   node scripts/engine-numbers.mjs --check  # exit 1 if the doc is stale (sheet.sh / CI)
// --check also guards the film's data against the voice: src/data/scenes.json must end (max scene.end) and
// src/data/captions.json's last page must end (e) exactly on assets/timing.json `duration` (else: STALE, exit 1), and
// every time-of-day relight row must stay at least one palette step off its sky (relightProblems in src/lib/theme.ts).
import path from 'node:path';
import fs from 'node:fs';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {buildSync} from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'node_modules/.cache/engine-numbers/theme.mjs');
fs.mkdirSync(path.dirname(out), {recursive: true});
buildSync({entryPoints: [path.join(root, 'src/lib/theme.ts')], bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error'});
const T = await import(pathToFileURL(out).href + `?v=${Date.now()}`);

const {skyCaption: C, world: W, safe: S, sunWorld: SUN, depthInk: D, skies: K, skyHighlightBox: HB, todSky, todTone} = T;
const lines = [
  '| token | value |',
  '|---|---|',
  `| caption font | Patrick Hand ('${T.type.family}') **${C.size} px**, centred on x **${C.cx}**, max line **${C.maxWidth} px** (\`skyCaption\`) |`,
  `| caption baselines | line 1 **y ${C.line1}**, line 2 **y ${C.line2}**, one-line page **y ${C.oneLine}** |`,
  `| caption band (clip window) | **y ${C.clipTop}-${C.clipBottom}**: keep busy detail, skyline tops and sky band steps out of it (tops below y 600) |`,
  `| caption motion | \`${C.motion}\` (reference 1's measured scroll / rise / wipe) |`,
  `| sky highlight box | top ${HB.topEm} em, bottom ${HB.bottomEm} em, padding ${HB.padEm} em both sides, radius ${HB.radiusEm} em, trailing punctuation inside (\`skyHighlightBox\`) |`,
  `| world | ${W.w} x ${W.h} px, horizon **y ${W.horizon}**, vanishing point **[${W.vp.join(', ')}]**, bleed **${W.bleed} px** (\`world\`) |`,
  `| sun | centre **(${SUN.cx}, ${SUN.cy})**, r **${SUN.r}** (\`sunWorld\`; baseline r 94-120, peaks only 270-490) |`,
  `| safe zones | UI covers y < ${S.top}, y > ${S.bottom}, right rail x > ${S.rail.x} for y ${S.rail.y0}-${S.rail.y1}; key action inside x ${S.action.x0}-${S.action.x1}, y ${S.action.y0}-${S.action.y1} (\`safe\`) |`,
  `| ink by depth | front ${D.front}, mid ${D.mid}, far ${D.far}, hair ${D.hair} px; far layers no ink (\`depthInk\`) |`,
  `| skies | day ${K.day}, golden ${K.golden}, dusk ${K.dusk}, night ${K.night}, deep ${K.deep} (\`skies\`) |`,
  `| time of day | sky ${Object.entries(todSky).map(([k, v]) => `${k} ${v}`).join(', ')}; caption tone ${Object.entries(todTone).map(([k, v]) => `${k} ${v}`).join(', ')} (\`todSky\`, \`todTone\`) |`,
];
const block = `<!-- numbers:begin (generated by scripts/engine-numbers.mjs from src/lib/theme.ts: do not edit by hand) -->\n${lines.join('\n')}\n<!-- numbers:end -->`;
// ---- data guards (the cut list / captions on the current voice)
const dataProblems = [];
const readJson = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
try {
  const voDur = Number(readJson('assets/timing.json').duration);
  const scenes = readJson('src/data/scenes.json');
  const caps = readJson('src/data/captions.json');
  const filmEnd = Math.max(...scenes.map((s) => s.end));
  if (Math.abs(filmEnd - voDur) > 0.002) dataProblems.push(`src/data/scenes.json ends at ${filmEnd} s but the voice is ${voDur} s (run node scripts/gen-scenes.mjs)`);
  const capEnd = caps.length ? caps[caps.length - 1].e : NaN;
  if (Math.abs(capEnd - voDur) > 0.002) dataProblems.push(`src/data/captions.json ends at ${capEnd} s but the voice is ${voDur} s (run node scripts/gen-captions.mjs --storyboard)`);
} catch (e) {
  dataProblems.push(`could not read the film data: ${e.message}`);
}
if (typeof T.relightProblems === 'function') for (const p of T.relightProblems()) dataProblems.push(`relight: ${p}`);
const docPath = path.join(root, 'docs/ENGINE.md');
const doc = fs.readFileSync(docPath, 'utf8');
const re = /<!-- numbers:begin[^>]*-->[\s\S]*?<!-- numbers:end -->/;
if (!re.test(doc)) {
  console.error('[engine-numbers] no <!-- numbers:begin --> block in docs/ENGINE.md');
  process.exit(2);
}
const next = doc.replace(re, block);
if (process.argv.includes('--check')) {
  let bad = false;
  if (next !== doc) {
    console.error('[engine-numbers] docs/ENGINE.md numbers are STALE: run node scripts/engine-numbers.mjs');
    bad = true;
  }
  for (const p of dataProblems) {
    console.error(`[engine-numbers] STALE data: ${p}`);
    bad = true;
  }
  if (bad) process.exit(1);
  console.error('[engine-numbers] docs/ENGINE.md numbers match theme.ts; scenes.json and captions.json end on the voice');
} else {
  fs.writeFileSync(docPath, next);
  console.error('[engine-numbers] docs/ENGINE.md numbers block updated');
}
