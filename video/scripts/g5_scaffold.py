#!/usr/bin/env python3
"""g5_scaffold.py: start a video's G5 film from its locked G3 board (docs/G5_BLOCKING.md).

  python3 -I scripts/g5_scaffold.py --animatic public/v3/animatic.json --film src/v3/film --drop LOOP \
      [--loop-dur 0.3] [--end 41.15] [--board-import ../BoardPanel] [--force-placeholders]

Writes, from the board's panels (shots: id, s, e, transition, note):
  <film>/scenes.json            Film scenes: {id, start, end, transitionIn: {type: 'cut'}, captionTone: [{t: 0, tone:
                                'dark'}], note: "board: <transition (label)> | <note line 1> | <note line 2>"}; the last
                                panel ends on --end (default: the board's durationSec) and gets the house loop
                                transitionOut {type: 'unbuild', loop: true, dur: --loop-dur}.
  <film>/scenes/<ID>.tsx        a board placeholder per panel (ONLY if the file is missing, or with
                                --force-placeholders): <BoardPanel id="<ID>"/> plays the board panel in the Film engine.
  <film>/scenes/index.ts        the static registry (every panel imported by name; default export = the scene,
                                optional `Wiper` and `captionTone` exports).
--drop: board-only panels to leave out (e.g. the board's LOOP dissolve: the film loops with the un-build instead).
Every transitionIn is a cut (G5 rule: the board's transition labels are kept in `note`). Re-running never touches a
panel file a lane has replaced (unless --force-placeholders).
"""
import argparse
import json
import re
import sys
from pathlib import Path

PLACEHOLDER = """// Lane: replace this file with the real set (docs/G5_BLOCKING.md).
// {id} board placeholder: plays the locked G3 board panel "{id}" inside the Film engine (scene-local time t = board
// time - {s}). Contract: default-export a React.FC with no props; optional exports `Wiper` (foreground-wipe element)
// and `captionTone` (ToneKey[], overrides scenes.json for this panel).
import React from 'react';
import {{BoardPanel}} from '{board}';

const {comp}: React.FC = () => <BoardPanel id="{id}" />;
export default {comp};
"""

INDEX_HEAD = """// {film} scene registry (static: every panel imported by name; generated by scripts/g5_scaffold.py, the engine
// lane owns it). A panel module default-exports its scene (React.FC, no props) and may export `Wiper`
// (WiperComponent, for a foreground-wipe OUT of it) and `captionTone` (ToneKey[], scene-local t: overrides the
// panel's scenes.json captionTone, so a lane sets its own caption tone without touching a shared file).
import type React from 'react';
import type {{ToneKey, WiperProps}} from '{lib}/Film';
"""


def ident(pid: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_]", "_", pid)
    return s if not s[0].isdigit() else "_" + s


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--animatic", required=True)
    ap.add_argument("--film", required=True, help="the film folder, e.g. src/v3/film")
    ap.add_argument("--drop", nargs="*", default=[])
    ap.add_argument("--loop-dur", type=float, default=0.3)
    ap.add_argument("--end", type=float, default=None)
    ap.add_argument("--board-import", default="../BoardPanel", help="import path of BoardPanel from scenes/")
    ap.add_argument("--lib-import", default=None, help="import path of src/lib from scenes/ (default: computed)")
    ap.add_argument("--force-placeholders", action="store_true")
    a = ap.parse_args()

    an = json.loads(Path(a.animatic).read_text(encoding="utf8"))
    shots = [s for s in an["shots"] if s["id"] not in set(a.drop)]
    end = a.end if a.end is not None else float(an["durationSec"])
    film = Path(a.film)
    (film / "scenes").mkdir(parents=True, exist_ok=True)

    scenes = []
    for i, s in enumerate(shots):
        tr = s.get("transition", {})
        label = f"{tr.get('type', 'cut')}" + (f" ({tr['label']})" if tr.get("label") else "")
        note_lines = [x.strip() for x in (s.get("note") or "").split("\n") if x.strip()]
        sc = {
            "id": s["id"],
            "start": round(float(s["s"]), 3),
            "end": round(end if i == len(shots) - 1 else float(s["e"]), 3),
            "transitionIn": {"type": "cut"},
            "captionTone": [{"t": 0, "tone": "dark"}],
            "note": " | ".join([f"board: {label}"] + note_lines),
        }
        if i == len(shots) - 1:
            sc["transitionOut"] = {"type": "unbuild", "loop": True, "dur": a.loop_dur}
        scenes.append(sc)
    for i in range(1, len(scenes)):
        if abs(scenes[i]["start"] - scenes[i - 1]["end"]) > 1e-6:
            print(f"[g5_scaffold] WARN gap/overlap between {scenes[i - 1]['id']} and {scenes[i]['id']}", file=sys.stderr)
    body = "[\n" + ",\n".join("  " + json.dumps(sc, ensure_ascii=False) for sc in scenes) + "\n]\n"
    (film / "scenes.json").write_text(body, encoding="utf8")

    wrote = []
    for s in shots:
        f = film / "scenes" / f"{s['id']}.tsx"
        if f.exists() and not a.force_placeholders:
            continue
        f.write_text(PLACEHOLDER.format(id=s["id"], s=s["s"], board=a.board_import, comp=ident(s["id"])), encoding="utf8")
        wrote.append(f.name)

    # src/lib relative to <film>/scenes
    lib = a.lib_import
    if lib is None:
        scenes_dir = (film / "scenes").resolve()
        src = next((p for p in [scenes_dir, *scenes_dir.parents] if p.name == "src"), None)
        rel = Path(*[".."] * (len(scenes_dir.relative_to(src).parts))) if src else Path("../../..")
        lib = (rel / "lib").as_posix()
    lines = [INDEX_HEAD.format(film=film.as_posix(), lib=lib)]
    for s in shots:
        lines.append(f"import * as {ident(s['id'])} from './{s['id']}';")
    lines.append("")
    lines.append("type PanelModule = {default: React.FC; Wiper?: React.FC<WiperProps>; captionTone?: ToneKey[]};")
    lines.append("const PANELS: Record<string, PanelModule> = {" + ", ".join(f"{json.dumps(s['id'])}: {ident(s['id'])}" for s in shots) + "};")
    lines.append("")
    lines.append("export const sceneComponents: Record<string, React.FC> = {};")
    lines.append("export const sceneWipers: Record<string, React.FC<WiperProps>> = {};")
    lines.append("export const sceneTones: Record<string, ToneKey[]> = {};")
    lines.append("for (const [id, m] of Object.entries(PANELS)) {")
    lines.append("  sceneComponents[id] = m.default;")
    lines.append("  if (typeof m.Wiper === 'function') sceneWipers[id] = m.Wiper;")
    lines.append("  if (Array.isArray(m.captionTone) && m.captionTone.length) sceneTones[id] = m.captionTone;")
    lines.append("}")
    (film / "scenes" / "index.ts").write_text("\n".join(lines) + "\n", encoding="utf8")
    print(f"[g5_scaffold] {len(scenes)} scenes -> {film / 'scenes.json'} ({scenes[0]['start']}..{scenes[-1]['end']} s); "
          f"placeholders written: {', '.join(wrote) or 'none (all exist)'}; registry -> {film / 'scenes' / 'index.ts'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
