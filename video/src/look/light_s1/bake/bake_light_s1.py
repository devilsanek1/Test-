#!/usr/bin/env python3
"""bake_light_s1.py: the LIGHT AND TEXTURE PROOF's bake (docs/look/organic/light_proof.md §2). From the engine's parts
renders of v6's scene 1 (render_many.mjs: every segment alone on a black and on a white slab, and the static base),
it lights the static picture (light.py), keys and grains it for look 'full' (key.py, texture.py), and solves each
slot's maps against the base (solve.py), writing them where the composition imports them:
    src/look/light_s1/maps/<look>/*.lmap.png  and  src/look/light_s1/maps.ts
Seeded and deterministic (two runs give the same bytes). From video/:
    python3 -B src/look/light_s1/bake/bake_light_s1.py --parts /tmp/organic/light_proof/parts [--preview DIR]
"""
import argparse
import hashlib
import json
import os
import sys
import time

import numpy as np

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from common import (H, W, Lstar, SLOTS, all_alphas, carriers, load_srgb, save_srgb, to_srgb)  # noqa: E402
from labels import labels  # noqa: E402
import light as LT  # noqa: E402
import solve as SV  # noqa: E402
import key as KY  # noqa: E402
import texture as TX  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, '..'))           # src/look/light_s1
MAPS_DIR = os.path.join(ROOT, 'maps')


def md5(path):
    return hashlib.md5(open(path, 'rb').read()).hexdigest()


def write_maps_ts(manifest):
    lines = ['// GENERATED by src/look/light_s1/bake/bake_light_s1.py (light_proof.md §2): the baked per-plane maps of the',
             '// light proof, by look. Do not edit by hand; rerun the bake.',
             "import type {MapSet} from './context';"]
    imports = []
    body = ['', "export const MAPS: Record<'light' | 'full', MapSet> = {"]
    for look in ('light', 'full'):
        m = manifest.get(look, {'slots': {}, 'live': {}})
        body.append(f'  {look}: {{')
        body.append('    slots: {')
        for slot in SLOTS:
            rows = m['slots'].get(slot)
            if not rows:
                continue
            items = []
            for r in rows:
                var = f"{look}_{r['file'].replace('.lmap.png', '').replace('-', '_')}"
                imports.append(f"import {var} from './maps/{look}/{r['file']}';")
                items.append(f"{{src: {var}, box: [{', '.join(str(v) for v in r['box'])}], blend: '{r['blend']}'}}")
            body.append(f"      {slot}: [{', '.join(items)}],")
        body.append('    },')
        live = m.get('live', {})
        lv = []
        if 'pool' in live:
            r = live['pool']
            var = f'{look}_pool'
            imports.append(f"import {var} from './maps/{look}/{r['file']}';")
            lv.append(f"pool: {{src: {var}, box: [{', '.join(str(v) for v in r['box'])}], blend: 'screen'}}")
        if 'doorBlur' in live:
            r = live['doorBlur']
            var = f'{look}_doorblur'
            imports.append(f"import {var} from './maps/{look}/{r['file']}';")
            lv.append(f"doorBlur: {{src: {var}, box: [{', '.join(str(v) for v in r['box'])}]}}")
        if 'grain' in live:
            r = live['grain']
            var = f'{look}_grain'
            imports.append(f"import {var} from './maps/{look}/{r['file']}';")
            lv.append(f"grain: {{src: {var}, size: {r['size']}}}")
        body.append(f"    live: {{{', '.join(lv)}}},")
        body.append('  },')
    body.append('};')
    with open(os.path.join(ROOT, 'maps.ts'), 'w') as fh:
        fh.write('\n'.join(lines + imports + body) + '\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--parts', default='/tmp/organic/light_proof/parts')
    ap.add_argument('--looks', default='light,full')
    ap.add_argument('--preview', default='')
    a = ap.parse_args()
    t0 = time.time()
    A = all_alphas(a.parts)
    base = load_srgb(f'{a.parts}/base_static.png')
    L, vis = labels(a.parts, A, base)
    car = carriers(A)
    t_in = time.time() - t0
    lit, lit_pool, parts = LT.light(base, L, vis, A, return_parts=True)
    # the key's one hot accent: where the door's light is (the lobby, its bloom, its pool, its column in the canal)
    KY.set_accent(np.clip(L['lobby'] + 1.4 * parts['bloom_door'] + 1.2 * parts['pool'] + 1.5 * parts['column'], 0, 1))
    T_light = to_srgb(LT.knee(lit))
    T_light_pool = to_srgb(LT.knee(lit_pool))
    t_light = time.time() - t0 - t_in
    manifest = {}
    report = {'inputs_s': round(t_in, 2), 'light_s': round(t_light, 2), 'looks': {}}
    ball = load_srgb(f'{a.parts}/base_all.png')
    mv = np.clip(A['her'] + A['pip'] + A['pipshadows'] + A['particles'], 0, 1)[..., None]
    for look in a.looks.split(','):
        tl = time.time()
        if look == 'light':
            T, Tp = T_light, T_light_pool
        else:
            T, Tp = KY.key(T_light, L, base), KY.key(T_light_pool, L, base)
            T, Tp = TX.grain_static(T, L), TX.grain_static(Tp, L)
        out_dir = os.path.join(MAPS_DIR, look)
        if os.path.isdir(out_dir):
            for f in os.listdir(out_dir):
                if f.endswith('.lmap.png'):
                    os.remove(os.path.join(out_dir, f))
        rows, comp, sizes = SV.solve_slots(base, T, car, L, out_dir, look)
        sub = SV.slot_pixels(car, L)['subject'] & (LT.pool_field() > 0.004)
        pool, comp = SV.solve_screen_layer(comp, Tp, sub, out_dir, 'pool_scr.lmap.png', f'{look}/pool')
        live = {}
        if pool:
            live['pool'] = pool
        img, bx = LT.door_blur(LT.knee(lit if look == 'light' else lit), L)
        if look == 'full':
            img = KY.key(img, None, None, flat=True)
        SV.write_png(os.path.join(out_dir, 'doorblur.lmap.png'), img)
        live['doorBlur'] = dict(file='doorblur.lmap.png', box=list(bx))
        if look == 'full':
            tile, size = TX.grain_tile()
            SV.write_png(os.path.join(out_dir, 'grain.lmap.png'), tile)
            live['grain'] = dict(file='grain.lmap.png', size=size)
        manifest[look] = {'slots': rows, 'live': live}
        err = np.abs(comp - T)
        cover = np.zeros((H, W), bool)
        for m in SV.slot_pixels(car, L).values():
            cover |= m
        files = sorted(f for f in os.listdir(out_dir) if f.endswith('.lmap.png'))
        report['looks'][look] = {
            'bake_s': round(time.time() - tl, 2),
            'maps': {s: [dict(r, bytes=os.path.getsize(os.path.join(out_dir, r['file']))) for r in rr] for s, rr in rows.items()},
            'pool': pool,
            'bytes_total': int(sum(os.path.getsize(os.path.join(out_dir, f)) for f in files)),
            'solve_check_max_code': float(np.round(err[cover & ~(SV.slot_pixels(car, L)['subject'] & (LT.pool_field() > 0.004))].max() * 255, 2)),
            'md5': {f: md5(os.path.join(out_dir, f)) for f in files},
        }
        if a.preview:
            prev = comp * (1 - mv) + ball * mv
            save_srgb(os.path.join(a.preview, f'preview_{look}.png'), prev)
            save_srgb(os.path.join(a.preview, f'target_{look}.png'), T)
    write_maps_ts(manifest)
    report['total_s'] = round(time.time() - t0, 2)
    report['sun'] = parts['sun']
    if a.preview:
        os.makedirs(a.preview, exist_ok=True)
        with open(os.path.join(a.preview, 'bake_report.json'), 'w') as fh:
            json.dump(report, fh, indent=1)
        np.savez_compressed(os.path.join(a.preview, 'bake_parts.npz'), canopy=parts['canopy'], pool=parts['pool'], rims=parts['rims'],
                            S=parts['S'], bloom_sun=parts['bloom_sun'], bloom_door=parts['bloom_door'])
    print(json.dumps({k: v for k, v in report.items() if k != 'looks'}))
    for look, r in report['looks'].items():
        print(look, 'bake', r['bake_s'], 's; maps', sum(len(v) for v in r['maps'].values()), '+ pool; bytes', r['bytes_total'], '; solve check max', r['solve_check_max_code'], 'code')


if __name__ == '__main__':
    main()
