// PEOPLE v4 (docs/look/people_design/faces_v2/V4.md): THE FACES as authored pen curves. Her B "cute" and his A "clean"
// (faces_v2/RECIPE.md) redrawn the way an illustrator draws them: each contour a few deliberate nodes (pen.ts), the
// curvature varying (long flat runs, tight turns at the nose's tip, the lips, the chin), every join tangent-continuous.
// Head units as before: the skull's height = 1 (crown -0.5, chin 0.5), origin at the skull's centre, y down, the face
// toward screen-left. The CRANIUM (the crown and the back of the head) is the current code's own outline for each view,
// kept EXACTLY (pen.ts rpolySegs over graphic_faces/head.ts's points), so every hair shape made for the current heads
// still fits; only the face plane, the brow, the nose, the lips, the chin, the jaw, the ear and the neck are new.
// Three views, each drawn on its own like a 2D cut-out rig's head turnaround: p = profile (yaw -90), q = 3/4 (yaw -36),
// l = the lost profile (yaw -138).
import type {V2} from '../graphic/geo';
import {n, rpolySegs, type PNode, type Seg} from './pen';

export type Sex = 'f' | 'm';
export type FaceView = 'p' | 'q' | 'l';

/** A tapered stroke: its centre line and widest width; prof picks the width profile (head.ts). */
export type Stroke = {line: PNode[]; w: number; prof?: 'lash' | 'brow' | 'comma'};
/** An open eye (the variant): the white (the iris is clipped by it), the iris's centre and radii, the upper lid. */
export type EyeOpen = {white: PNode[]; iris: {c: V2; rx: number; ry: number}; lid: Stroke};
export type ViewDesign = {
  view: FaceView;
  yaw: number;
  /** the kept cranium, from the face's end back round to its start */
  cranium: Seg[];
  /** the face's contour (pen nodes), from the cranium's end round to its start */
  face: PNode[];
  /** the terminator, top to bottom: the shade plane lies on the `away` side */
  term: PNode[];
  away: V2;
  /** the warm tones (centre, radii, angle, strength) */
  cheeks: {c: V2; rx: number; ry: number; a: number; k: number}[];
  /** the lips' tone; `fade` = the gradient's full end and its gone end */
  lips: {nodes: PNode[]; fade: [V2, V2]}[];
  /** the nose's shade (3/4: the near side of the lower nose and under the tip) and its one crease */
  noseShade?: PNode[];
  wing?: Stroke;
  lashes: Stroke[];
  open: EyeOpen[];
  brows: Stroke[];
  /** the ear: centre, size, tilt; back = seen from behind (one shape, no notch, the helix toward screen-left) */
  ear?: {c: V2; h: number; w: number; tilt: number; back?: boolean};
  neck: {front: PNode[]; back: PNode[]};
  /** the jaw's cast shadow on the neck, along this line */
  jawShadow?: PNode[];
  /** the lost profile's nape: below this line the head is in the neck's shade (under the hairline) */
  under?: PNode[];
  /** the landmarks the hair and props use */
  lm: {faceX: number; nape: V2; jawAngle: V2; earC: V2; eyeY: number};
};

