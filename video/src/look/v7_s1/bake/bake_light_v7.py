#!/usr/bin/env python3
"""bake_light_v7.py: v7's light bake (ORGANIC.md §6 step 2; light_proof.md §2's method on v7's keyed, cut scene). From
the engine's parts renders of V7S1 (render_many.mjs: every segment alone on a black and on a white slab, the static
base, the marker render), it lights the static picture (v7light.py) and solves each slot's maps against the base with
the light proof's solver (light_s1/bake/solve.py, imported, its slot table swapped for v7's), writing them where the
composition imports them:
    look v7a:  src/look/v7_s1/maps/v7a/*.v7map.png  and  src/look/v7_s1/maps.ts      (the first half: MAPS)
    look v7:   src/look/v7_s1/maps/v7/*.v7map.png   and  src/look/v7_s1/maps_v7.ts   (the second half: MAPS_V7)
Look v7 (NOTES.md "v7") solves against the parts renders WITH the painted pieces (step 3), its surface labels read from
the flat parts of look v7a (`--labels`: the same geometry, the keyed flat colours, so a painted mark never changes what
surface a pixel is), adds the quay's light (v7light.quay_light: the sky's sheen in the wet, the door's light coming
across the quay toward us) and, with `--paper`, step 5: the one paper folded into the target before the solve (so it
rides each plane's maps) and the movers' grain tile (lib/light2 GrainOn).
The key is NOT in the maps: the maps carry the light only (the key is at the source: palette_v7.ts and the painter).
Seeded and deterministic (two runs give the same bytes). From video/:
    python3 -B src/look/v7_s1/bake/bake_light_v7.py --parts <dir> [--look v7 --labels <v7a parts> --paper] [--preview DIR]"""
import argparse
import hashlib
import json
import os
import sys
import time

import numpy as np

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import v7common as C  # noqa: E402
from v7common import H, W, SLOTS, all_alphas, carriers, load_srgb, save_srgb, to_lin, to_srgb  # noqa: E402
from v7labels import labels  # noqa: E402
import v7light as VL  # noqa: E402
import light as LT  # noqa: E402  (light_s1/bake/light.py)
import solve as SV  # noqa: E402  (light_s1/bake/solve.py)
import texture as TX  # noqa: E402  (light_s1/bake/texture.py: the one paper)

SV.slot_pixels = C.slot_pixels      # the light proof's solver on v7's slots
ROOT = os.path.abspath(os.path.join(HERE, '..'))           # src/look/v7_s1
MAPS_DIR = os.path.join(ROOT, 'maps', 'v7a')
EXT = '.v7map.png'
#: per look: the maps' folder, the generated module and its export
LOOKS = {'v7a': ('v7a', 'maps.ts', 'MAPS'), 'v7': ('v7', 'maps_v7.ts', 'MAPS_V7')}
LOOK = 'v7a'


def md5(path):
    return hashlib.md5(open(path, 'rb').read()).hexdigest()


def write_maps_ts(rows, live):
    sub, ts_name, export = LOOKS[LOOK]
    note = 'NOTES.md v7a' if LOOK == 'v7a' else 'NOTES.md v7'
    flag = '' if LOOK == 'v7a' else ' --look v7'
    lines = [f"// GENERATED by src/look/v7_s1/bake/bake_light_v7.py{flag} (the light bake; {note}): the baked per-plane maps of",
             f"// look '{LOOK}'. Do not edit by hand; rerun the bake.",
             "import type {MapSet} from './context';"]
    imports, body = [], ['', f'export const {export}: MapSet = {{', '  slots: {']
    for slot in SLOTS:
        rr = rows.get(slot)
        if not rr:
            continue
        items = []
        for r in rr:
            var = 'm_' + r['file'].replace(EXT, '').replace('-', '_')
            imports.append(f"import {var} from './maps/{sub}/{r['file']}';")
            items.append(f"{{src: {var}, box: [{', '.join(str(v) for v in r['box'])}], blend: '{r['blend']}'}}")
        body.append(f"    {slot}: [{', '.join(items)}],")
    body.append('  },')
    lv = []
    if 'pool' in live:
        r = live['pool']
        imports.append(f"import m_pool from './maps/{sub}/{r['file']}';")
        lv.append(f"pool: {{src: m_pool, box: [{', '.join(str(v) for v in r['box'])}], blend: 'screen'}}")
    if 'doorBlur' in live:
        r = live['doorBlur']
        imports.append(f"import m_doorblur from './maps/{sub}/{r['file']}';")
        lv.append(f"doorBlur: {{src: m_doorblur, box: [{', '.join(str(v) for v in r['box'])}]}}")
    if 'grain' in live:
        r = live['grain']
        imports.append(f"import m_grain from './maps/{sub}/{r['file']}';")
        lv.append(f"grain: {{src: m_grain, size: {r['size']}}}")
    body.append(f"  live: {{{', '.join(lv)}}},")
    body.append('};')
    with open(os.path.join(ROOT, ts_name), 'w') as fh:
        fh.write('\n'.join(lines + imports + body) + '\n')


def rename(rows_or_row):
    """The solver writes '<name>.lmap.png' (the light proof's suffix): v7's are '<name>.v7map.png' (its own module
    declaration, assets.d.ts)."""
    rr = rows_or_row if isinstance(rows_or_row, list) else [rows_or_row]
    for r in rr:
        if r['file'].endswith('.lmap.png'):
            new = r['file'].replace('.lmap.png', EXT)
            os.replace(os.path.join(MAPS_DIR, r['file']), os.path.join(MAPS_DIR, new))
            r['file'] = new


def main():
    global MAPS_DIR, LOOK
    ap = argparse.ArgumentParser()
    ap.add_argument('--parts', required=True)
    ap.add_argument('--look', default='v7a', choices=sorted(LOOKS))
    ap.add_argument('--labels', default='', help="the flat parts (look v7a) the surface labels are read from (look v7)")
    ap.add_argument('--paper', action='store_true', help='step 5: the one paper in the target and the movers\' grain tile')
    ap.add_argument('--preview', default='')
    a = ap.parse_args()
    LOOK = a.look
    MAPS_DIR = os.path.join(ROOT, 'maps', LOOKS[LOOK][0])
    t0 = time.time()
    A = all_alphas(a.parts)
    base = load_srgb(f'{a.parts}/base_static.png')
    if a.labels:
        # the surfaces from the flat scene (the same geometry, its keyed flat colours): a painted mark never changes
        # what surface a pixel is, so the pieces are lit as the faces they repaint
        A_flat = all_alphas(a.labels)
        L, vis = labels(a.labels, A_flat, load_srgb(f'{a.labels}/base_static.png'))
    else:
        L, vis = labels(a.parts, A, base)
    car = carriers(A)
    t_in = time.time() - t0
    lit, lit_pool, parts = VL.light_v7(base, L, vis, A, dose=VL.DOSE_V7 if LOOK == 'v7' else VL.DOSE)
    B_lin = to_lin(base)
    T = to_srgb(LT.knee(lit, base=B_lin))
    Tp = to_srgb(LT.knee(lit_pool, base=B_lin))
    if a.paper:
        # step 5: the one paper (light_s1 texture.py: tooth, fibre, mottle, soft-light round mid-grey, the band at 12 %),
        # folded into the target, so each plane's maps carry it and it rides that plane's float
        T, Tp = TX.grain_static(T, L), TX.grain_static(Tp, L)
    t_light = time.time() - t0 - t_in
    os.makedirs(MAPS_DIR, exist_ok=True)
    for f in os.listdir(MAPS_DIR):
        if f.endswith(EXT) or f.endswith('.lmap.png'):
            os.remove(os.path.join(MAPS_DIR, f))
    tl = time.time()
    rows, comp, _ = SV.solve_slots(base, T, car, L, MAPS_DIR, LOOK)
    for rr in rows.values():
        rename(rr)
    sub = C.slot_pixels(car, L)['subject'] & (LT.pool_field() > 0.004)
    pool, comp = SV.solve_screen_layer(comp, Tp, sub, MAPS_DIR, 'pool_scr.lmap.png', f'{LOOK}/pool')
    live = {}
    if pool:
        rename(pool)
        live['pool'] = pool
    img, bx = LT.door_blur(LT.knee(lit), L)
    SV.write_png(os.path.join(MAPS_DIR, 'doorblur' + EXT), img)
    live['doorBlur'] = dict(file='doorblur' + EXT, box=list(bx))
    if a.paper:
        tile, size = TX.grain_tile()
        SV.write_png(os.path.join(MAPS_DIR, 'grain' + EXT), tile)
        live['grain'] = dict(file='grain' + EXT, size=size)
    write_maps_ts(rows, live)
    files = sorted(f for f in os.listdir(MAPS_DIR) if f.endswith(EXT))
    cover = np.zeros((H, W), bool)
    for m in C.slot_pixels(car, L).values():
        cover |= m
    err = np.abs(comp - T)
    report = {
        'inputs_s': round(t_in, 2), 'light_s': round(t_light, 2), 'solve_s': round(time.time() - tl, 2),
        'maps': {s: rr for s, rr in rows.items()}, 'pool': pool,
        'bytes_total': int(sum(os.path.getsize(os.path.join(MAPS_DIR, f)) for f in files)),
        'solve_check_max_code': float(np.round(err[cover & ~sub].max() * 255, 2)),
        'md5': {f: md5(os.path.join(MAPS_DIR, f)) for f in files},
        'sun': parts['sun'], 'total_s': round(time.time() - t0, 2),
    }
    if a.preview:
        os.makedirs(a.preview, exist_ok=True)
        ball = load_srgb(f'{a.parts}/base_all.png')
        mv = np.clip(A['her'] + A['pip'] + A['particles'], 0, 1)[..., None]
        save_srgb(os.path.join(a.preview, f'preview_{LOOK}.png'), comp * (1 - mv) + ball * mv)
        save_srgb(os.path.join(a.preview, f'target_{LOOK}.png'), T)
        with open(os.path.join(a.preview, 'bake_report.json'), 'w') as fh:
            json.dump(report, fh, indent=1)
        np.savez_compressed(os.path.join(a.preview, 'bake_parts.npz'), canopy=parts['canopy'], holes=parts['holes'],
                            rims=parts['rims'], E=parts['E'].astype(np.float16), litwin=L['litwin'], lobby=L['lobby'],
                            glass=L['glass'], wall=L['wall'], water=L['water'], bank=L['bank'], near=L['near'],
                            towpath=L['towpath'], boats=L['boats'], sky=L['sky'], cloud=L['cloud'],
                            farroofs=L['farroofs'], fartower=L['fartower'], bridge=L['bridge'])
    print(json.dumps({k: v for k, v in report.items() if k not in ('maps', 'md5')}))
    print('maps', sum(len(v) for v in rows.values()), '+ pool + door blur; bytes', report['bytes_total'])


if __name__ == '__main__':
    main()
