#!/usr/bin/env python3
"""paint_v7.py: PAINTER v7, step 3 (ORGANIC.md §6 step 3; NOTES.md "v7"): the organic pieces of look 'v7', painted
through MyPaint's brush engine (peinten, vendored in the scratch as organic proof 1 runs it: OC_PEINTEN, OC_BRUSHES)
from v7a's flat parts renders (look 'v7a': the keyed vector scene, no pieces), written where the composition imports
them:
    src/look/v7_s1/paint/<name>.v7piece.png   and   src/look/v7_s1/paint_v7.ts (the generated registry: import + box)
Each piece is the MATERIAL in the keyed colours; the light bake (bake_light_v7.py --look v7) then solves each plane's
maps against what the slots draw, so every piece is lit by the one rig, never painted lit. Seeded: two runs, the same
bytes. Run with the organic proof's venv (FastNoiseLite), from video/:
    OC_SCRATCH=<scratch> <venv>/python -B src/look/v7_s1/bake/paint_v7.py --flat <v7a parts dir> [--only quay,facade,leaves]"""
import argparse
import hashlib
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True
ROOT = os.path.abspath(os.path.join(HERE, '..'))            # src/look/v7_s1
PAINT_DIR = os.path.join(ROOT, 'paint')
EXT = '.v7piece.png'

sys.path.insert(0, os.path.abspath(os.path.join(HERE, '..', '..', '..', '..', 'scripts', 'look', 'organic')))
import oc_lib as L  # noqa: E402  (organic proof 1's library: OKLab, noise, the stroke plan, MyPaint's bridge)

#: the pieces in drawing order: name -> (the slot it fills (pieces.tsx PieceName), the module that paints it)
PIECES = {
    'farcity': ('farcity', 'piece_farcity'),
    'quay': ('paving', 'piece_quay'),
    'facade': ('facade', 'piece_wing'),
    'prop': ('prop', 'piece_prop'),
}


def md5(path):
    return hashlib.md5(open(path, 'rb').read()).hexdigest()


def write_ts(rows):
    lines = ["// GENERATED by src/look/v7_s1/bake/paint_v7.py (the painter v7, step 3; NOTES.md v7): the painted pieces of look 'v7'",
             "// and their boxes in their layers' own px. Do not edit by hand; rerun the painter.",
             "import type {PieceName, V7Piece} from './pieces';"]
    body = ['', 'export const PIECES_V7: Partial<Record<PieceName, V7Piece>> = {']
    for name, (slot, _) in PIECES.items():
        r = rows.get(name)
        if not r:
            continue
        var = 'p_' + name
        lines.append(f"import {var} from './paint/{name}{EXT}';")
        body.append(f"  {slot}: {{src: {var}, box: [{', '.join(str(int(v)) for v in r['box'])}]}},")
    body.append('};')
    with open(os.path.join(ROOT, 'paint_v7.ts'), 'w') as fh:
        fh.write('\n'.join(lines + body) + '\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--flat', required=True, help="v7a's parts renders (the flat keyed scene: the painter's input)")
    ap.add_argument('--only', default='', help='comma list of pieces to repaint (the others are kept as they are)')
    ap.add_argument('--drop', default='', help='comma list of pieces to remove from the registry')
    a = ap.parse_args()
    os.makedirs(PAINT_DIR, exist_ok=True)
    man_path = os.path.join(PAINT_DIR, 'pieces.json')
    man = json.load(open(man_path)) if os.path.exists(man_path) else {}
    only = [s for s in a.only.split(',') if s] or list(PIECES)
    for name in [s for s in a.drop.split(',') if s]:
        man.pop(name, None)
        p = os.path.join(PAINT_DIR, name + EXT)
        if os.path.exists(p):
            os.remove(p)
    for name in only:
        slot, mod = PIECES[name]
        t0 = time.time()
        m = __import__(mod)
        rgba, stats = m.make(a.flat)
        out = os.path.join(PAINT_DIR, name + EXT)
        L.save_rgba(out, rgba)
        stats.update(slot=slot, seconds=round(time.time() - t0, 2), bytes=os.path.getsize(out), md5=md5(out))
        man[name] = stats
        print(name, json.dumps({k: v for k, v in stats.items() if k != 'strokes'}), stats.get('strokes'))
    with open(man_path, 'w') as fh:
        json.dump(man, fh, indent=1, sort_keys=True)
    write_ts(man)


if __name__ == '__main__':
    main()
