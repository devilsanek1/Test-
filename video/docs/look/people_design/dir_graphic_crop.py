#!/usr/bin/env python3
"""The MODERN GRAPHIC direction's scene test: a crop of the painted still v6 at the doorway, BEFORE (as painted, with
the old her) and AFTER (the old her painted out, so the sheet can stand our figure on the same spot), saved as a data
module the sheet imports (src/look/people_dirs/graphic/doorway.ts). Deterministic. Run from video/:
    python3 docs/look/people_design/dir_graphic_crop.py
The old her stood with her soles at y ~1083, centred at x ~684, ~154 px tall (frame px of 1080 x 1920).
"""
import base64
import io
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / 'docs/studies/2026-10-28_city_posters/paint_test/paint_still_v6.png'
OUT = ROOT / 'src/look/people_dirs/graphic/doorway.ts'

CROP = (380, 760, 900, 1160)  # x0, y0, x1, y1 (520 x 400): the lit doorway, the wall, the lamp posts, the pier's edge
BOX = (659, 919, 707, 1093)  # the old her (frame px), rebuilt row by row from the clean wall beside her
FRAME_OUT = (107, 75, 95)
FRAME_IN = (216, 172, 116)
BENCH = (111, 72, 73)
SIDE_WALL = (247, 207, 134)
SIDE_EDGE = (230, 191, 123)
DOOR_POST = (75, 42, 30)
DOOR_EDGE = (72, 44, 35)


def patched(im: Image.Image) -> Image.Image:
    im = im.copy()
    px = im.load()
    x0, y0, x1, y1 = BOX
    for y in range(y0, y1):
        # the interior is flat by rows: take the clean wall left of the bench; below the threshold the pavement lies
        # in the door's cast shadow, so take it from the right of the box
        c = px[632, y] if y < 1082 else px[716, y]
        for x in range(x0, x1):
            px[x, y] = c
        if y < 1041:  # the interior's right side wall, down to the floor line
            for x in range(697, 705):
                px[x, y] = SIDE_WALL
            px[705, y] = SIDE_EDGE
        if y < 1076:
            px[706, y] = DOOR_POST
            px[707, y] = DOOR_POST
            px[708, y] = DOOR_EDGE  # the scarf's end crossed the door post here
    d = ImageDraw.Draw(im)
    d.rectangle((638, 923, 671, 950), fill=FRAME_OUT)  # the picture frame's right part
    d.rectangle((641, 926, 668, 947), fill=FRAME_IN)
    d.rectangle((649, 1014, 692, 1020), fill=BENCH)  # the bench's seat and right leg
    d.rectangle((685, 1020, 690, 1044), fill=BENCH)
    return im


def b64(im: Image.Image) -> str:
    buf = io.BytesIO()
    im.save(buf, format='PNG', optimize=True)
    return base64.b64encode(buf.getvalue()).decode('ascii')


def main():
    im = Image.open(SRC).convert('RGB')
    before = im.crop(CROP)
    after = patched(im).crop(CROP)
    x0, y0, x1, y1 = CROP
    OUT.write_text(
        '// GENERATED by docs/look/people_design/dir_graphic_crop.py: a crop of the painted still v6 at the doorway\n'
        f'// (frame px {x0},{y0} to {x1},{y1}), BEFORE (the old her) and AFTER (her painted out, for our figure).\n'
        f'export const DOOR_CROP = {{x: {x0}, y: {y0}, w: {x1 - x0}, h: {y1 - y0}}};\n'
        '/** Where the old her stood: her soles at y 1083, her centre at x 684 (frame px); she was ~154 px tall. */\n'
        'export const DOOR_SPOT = {x: 684, y: 1083, h: 154};\n'
        f"export const DOOR_BEFORE = 'data:image/png;base64,{b64(before)}';\n"
        f"export const DOOR_AFTER = 'data:image/png;base64,{b64(after)}';\n"
    )
    print('wrote', OUT, OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
