#!/usr/bin/env python3
"""The hair_v2 iteration 3's reference crops for the comparison sheets S8 and S9 (the owner's references beside our
cuts): each reference head cropped from refs_hair_2026-10-30/, enlarged 3x (LANCZOS) and saved as a JPEG data module
the sheets import (src/look/people_dirs/hair_v2/refs.ts; never video/public). Deterministic. Run from video/:
    python3 docs/look/people_design/hair_v2/refs_crops.py
"""
import base64
import io
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[4]
REFS = ROOT / 'docs/look/people_design/refs_hair_2026-10-30'
OUT = ROOT / 'src/look/people_dirs/hair_v2/refs.ts'
# id: (file, crop box in the original pixels)
CROPS = {
    'bob': ('03_students_and_sheet.jpg', (55, 100, 200, 240)),
    'swept': ('03_students_and_sheet.jpg', (415, 30, 575, 170)),
    'curls': ('03_students_and_sheet.jpg', (215, 700, 410, 870)),
    'blue': ('04_bassist_pencil.jpg', (55, 155, 265, 350)),
    'fall': ('05_girl_on_ledge.jpg', (175, 60, 325, 245)),
    'rear': ('02_street_cafe_graphic.jpg', (0, 50, 120, 210)),
}


def main() -> None:
    lines = ['// GENERATED by docs/look/people_design/hair_v2/refs_crops.py: the owner\'s hair references (refs_hair_2026-10-30),',
             '// each head cropped and enlarged 3x, as JPEG data for the comparison sheets S8 and S9 only.',
             'export type RefCrop = {src: string; w: number; h: number};',
             'export const REFS: Record<string, RefCrop> = {']
    for k, (f, box) in CROPS.items():
        im = Image.open(REFS / f).convert('RGB').crop(box)
        im = im.resize((im.width * 3, im.height * 3), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, format='JPEG', quality=88, optimize=True)
        b64 = base64.b64encode(buf.getvalue()).decode('ascii')
        lines.append(f"  {k}: {{src: 'data:image/jpeg;base64,{b64}', w: {im.width}, h: {im.height}}},")
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'{OUT}: {OUT.stat().st_size // 1024} KB')


if __name__ == '__main__':
    main()
