#!/usr/bin/env python3
"""The hair_v2 iteration's evening plate for S4 (the cast at film size in our night scene): the painted still v6, whole
(1080 x 1920), with the old her painted out (the doorway crop that dir_graphic_crop.py made, pasted back over the
frame), saved as a JPEG data module the sheet imports (src/look/people_dirs/hair_v2/plate.ts). Deterministic. Run from
video/:
    python3 docs/look/people_design/hair_v2/plate_v6.py
"""
import base64
import io
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[4]
SRC = ROOT / 'docs/studies/2026-10-28_city_posters/paint_test/paint_still_v6.png'
DOOR = ROOT / 'src/look/people_dirs/graphic/doorway.ts'
OUT = ROOT / 'src/look/people_dirs/hair_v2/plate.ts'


def main() -> None:
    frame = Image.open(SRC).convert('RGB')
    ts = DOOR.read_text()
    crop = re.search(r"export const DOOR_CROP = \{x: (\d+), y: (\d+), w: (\d+), h: (\d+)\}", ts)
    after = re.search(r"export const DOOR_AFTER = 'data:image/png;base64,([A-Za-z0-9+/=]+)'", ts)
    assert crop and after, 'doorway.ts changed shape'
    x, y = int(crop.group(1)), int(crop.group(2))
    door = Image.open(io.BytesIO(base64.b64decode(after.group(1)))).convert('RGB')
    frame.paste(door, (x, y))
    buf = io.BytesIO()
    frame.save(buf, format='JPEG', quality=86, optimize=True, progressive=True)
    b64 = base64.b64encode(buf.getvalue()).decode('ascii')
    OUT.write_text(
        '// GENERATED by docs/look/people_design/hair_v2/plate_v6.py: the painted still v6 (1080 x 1920), the old her\n'
        '// painted out (graphic/doorway.ts DOOR_AFTER pasted back at its crop), as a JPEG. For the S4 still only.\n'
        "export const PLATE_W = 1080;\nexport const PLATE_H = 1920;\n"
        f"export const PLATE_V6 = 'data:image/jpeg;base64,{b64}';\n"
    )
    print(f'{OUT}: {len(b64) // 1024} KB of base64')


if __name__ == '__main__':
    main()
