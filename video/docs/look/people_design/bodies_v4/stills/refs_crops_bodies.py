#!/usr/bin/env python3
"""bodies_v4: the reference crops the poses sheet needs beyond people_v4/refs.ts (ref 01's pair on the hill, ref 02's
walking woman), enlarged (LANCZOS) and saved as a JPEG data module the sheets import
(src/look/people_dirs/people_v4/refs5.ts; never video/public). Deterministic. Run from video/:
    python3 docs/look/people_design/bodies_v4/stills/refs_crops_bodies.py
"""
import base64
import io
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[5]
REFS = ROOT / 'docs/look/people_design/refs_hair_2026-10-30'
OUT = ROOT / 'src/look/people_dirs/people_v4/refs5.ts'
# id: (file, crop box in the original pixels, enlargement)
CROPS = {
    'hill01': ('01_pair_on_hill_wind.jpg', (70, 40, 380, 290), 2),
    'walk02': ('02_street_cafe_graphic.jpg', (0, 40, 168, 317), 2),
    'ledge05': ('05_girl_on_ledge.jpg', (90, 50, 420, 470), 1),
    'stand03': ('03_students_and_sheet.jpg', (0, 96, 236, 652), 1),
}


def main() -> None:
    lines = ["// GENERATED by docs/look/people_design/bodies_v4/stills/refs_crops_bodies.py: the owner's references",
             '// (refs_hair_2026-10-30) cropped and enlarged, as JPEG data for the bodies stills only.',
             "import type {RefCrop} from './refs';",
             'export const REFS5: Record<string, RefCrop> = {']
    for k, (f, box, z) in CROPS.items():
        im = Image.open(REFS / f).convert('RGB').crop(box)
        im = im.resize((im.width * z, im.height * z), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, format='JPEG', quality=86, optimize=True)
        b64 = base64.b64encode(buf.getvalue()).decode('ascii')
        lines.append(f"  {k}: {{src: 'data:image/jpeg;base64,{b64}', w: {im.width}, h: {im.height}}},")
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n')
    print('wrote', OUT, OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
