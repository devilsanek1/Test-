#!/usr/bin/env python3
"""faces_v2 v4: the reference crops for the stills 01-03 (the owner's references beside our faces and bodies): each
crop from refs_hair_2026-10-30/, enlarged (LANCZOS) and saved as a JPEG data module the sheets import
(src/look/people_dirs/people_v4/refs.ts; never video/public). Deterministic. Run from video/:
    python3 docs/look/people_design/faces_v2/stills_v4/refs_crops_v4.py
"""
import base64
import io
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[5]
REFS = ROOT / 'docs/look/people_design/refs_hair_2026-10-30'
OUT = ROOT / 'src/look/people_dirs/people_v4/refs.ts'
# id: (file, crop box in the original pixels, enlargement)
CROPS = {
    'her05': ('05_girl_on_ledge.jpg', (195, 70, 300, 200), 4),
    'body05': ('05_girl_on_ledge.jpg', (140, 60, 400, 450), 2),
    'girl03': ('03_students_and_sheet.jpg', (55, 100, 205, 250), 3),
    'boy03': ('03_students_and_sheet.jpg', (405, 30, 585, 250), 3),
    'pair03': ('03_students_and_sheet.jpg', (0, 60, 630, 660), 1),
    'bass04': ('04_bassist_pencil.jpg', (55, 150, 270, 360), 2),
}


def main() -> None:
    lines = ["// GENERATED by docs/look/people_design/faces_v2/stills_v4/refs_crops_v4.py: the owner's references",
             '// (refs_hair_2026-10-30) cropped and enlarged, as JPEG data for the v4 stills only.',
             'export type RefCrop = {src: string; w: number; h: number};',
             'export const REFS4: Record<string, RefCrop> = {']
    for k, (f, box, z) in CROPS.items():
        im = Image.open(REFS / f).convert('RGB').crop(box)
        im = im.resize((im.width * z, im.height * z), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, format='JPEG', quality=86, optimize=True)
        b64 = base64.b64encode(buf.getvalue()).decode('ascii')
        lines.append(f"  {k}: {{src: 'data:image/jpeg;base64,{b64}', w: {im.width}, h: {im.height}}},")
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n')
    print('wrote', OUT, OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
